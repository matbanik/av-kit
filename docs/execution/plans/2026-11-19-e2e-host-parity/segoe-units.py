"""Session 97 generator (task row 7; AC-161.3; D-1243): the Segoe UI glyph table in font units.

    uv run --no-sync python <plan>/segoe-units.py --out <file>     # write the module elsewhere
    uv run --no-sync python <plan>/segoe-units.py --write          # replace the tracked module
    uv run --no-sync python <plan>/segoe-units.py --check          # exit 0 when the module matches

It writes `ui/src/renderer/src/features/capture/capture-segoe-metrics.ts` (CRLF, as the file is
now). The module keeps the `SEGOE_UNITS` head (units per em 2048, ascender 2210) and replaces the
16 px table (`SEGOE_LA_BASE_SIZE`, `SegoeGlyph`, `SEGOE_LA_GLYPHS`) with `SegoeGlyphUnits` and
`SEGOE_UI_GLYPH_UNITS`: for each printable ASCII character (0x20 to 0x7E, 95 glyphs) its ink box
at the `ls` anchor (left, top, right, bottom; top is negative above the baseline) and its
advance, all in font units. They come from Pillow's FreeType at 2048 px, where one pixel is one
unit: `ImageFont.truetype(segoeui.ttf, 2048).getbbox(ch, anchor="ls")` and `getlength(ch)`.
It also writes `SEGOE_UI_KERN_UNITS` (expert pass M1): every printable ASCII pair whose kerning
is not zero, in font units, read the way the bake's basic layout reads it (raqm is absent, so
Pillow calls FreeType's `FT_Get_Kerning`). Pillow adds the pair's whole-pixel kerning to the pen
in 1/64 px, so at 2048 px `64 * (getlength(a + b) - getlength(a) - getlength(b))` is the pair's
value in font units (372 pairs at plan time; `AV` -117, `To` -211).

The font is `%WINDIR%/Fonts/segoeui.ttf`, the file the bake loads first
(`adapter.py` `FONT_CANDIDATES`). Its SHA-256 goes into the module's comment, so a font that
differs shows up as a `--check` failure. Every value must be a whole number (the advance too);
a fraction stops the run. The write is bytes, CRLF, UTF-8 with no BOM, ending in one CRLF.

Every write leaves no partial file (`write_new`; Session 95 RULE-1): `--out` creates its file
exclusively and removes it on a write error; `--write` writes `<file>.ehp-tmp` and replaces the
tracked file in one `os.replace`, so an error keeps the old bytes. `EHP_WRITE_FAULT=1` injects
that error after the create (task row 0 and the write rows test it).

Exit 0 on success (or a match with `--check`), 1 on a mismatch or a refused precondition, 2 on
an argument problem.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
MODULE = REPO / "ui/src/renderer/src/features/capture/capture-segoe-metrics.ts"
FONT = Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts" / "segoeui.ttf"
UNITS_PER_EM = 2048
ASCENDER = 2210
CHARS = [chr(code) for code in range(0x20, 0x7F)]


def font_units(font_path: Path) -> dict[str, tuple[int, int, int, int, int]]:
    from PIL import ImageFont

    big = ImageFont.truetype(str(font_path), UNITS_PER_EM)
    units: dict[str, tuple[int, int, int, int, int]] = {}
    for ch in CHARS:
        box = big.getbbox(ch, anchor="ls")
        length = big.getlength(ch)
        values = [*box, length]
        if any(float(v) != int(v) for v in values):
            raise ValueError(f"{ch!r}: a value is not a whole number of units: {values}")
        left, top, right, bottom = (int(v) for v in box)
        units[ch] = (left, top, right, bottom, int(length))
    return units


def font_kerning(font_path: Path) -> dict[str, int]:
    from PIL import ImageFont

    big = ImageFont.truetype(str(font_path), UNITS_PER_EM)
    length = {ch: big.getlength(ch) for ch in CHARS}
    kern: dict[str, int] = {}
    for a in CHARS:
        for b in CHARS:
            value = 64 * (big.getlength(a + b) - length[a] - length[b])
            if float(value) != int(value):
                raise ValueError(f"{a + b!r}: the kerning is not a whole number of units: {value}")
            if int(value):
                kern[a + b] = int(value)
    return kern


def render(
    units: dict[str, tuple[int, int, int, int, int]], kern: dict[str, int], font_sha: str
) -> bytes:
    lines = [
        "// SEGOE_UNITS (MEU-82, D-10): the head/hhea values of C:/Windows/Fonts/segoeui.ttf.",
        f"export const SEGOE_UI_UNITS_PER_EM = {UNITS_PER_EM}",
        f"export const SEGOE_UI_ASCENDER = {ASCENDER}",
        "// SEGOE_GLYPH_UNITS (MEU-161, D-1243): each printable ASCII glyph's ink box at the `ls`",
        "// anchor (t is negative above the baseline) and its advance, in font units, from",
        "// Pillow's FreeType at 2048 px. Generated by",
        "// docs/execution/plans/2026-11-19-e2e-host-parity/segoe-units.py from segoeui.ttf",
        f"// sha256 {font_sha}.",
        "export type SegoeGlyphUnits = { l: number; t: number; r: number; b: number; adv: number }",
        "export const SEGOE_UI_GLYPH_UNITS: Record<string, SegoeGlyphUnits> = {",
    ]
    for ch in CHARS:
        left, top, right, bottom, adv = units[ch]
        key = json.dumps(ch)
        lines.append(f"  {key}: {{ l: {left}, t: {top}, r: {right}, b: {bottom}, adv: {adv} }},")
    lines.append("}")
    lines.append(
        "// SEGOE_KERN_UNITS (MEU-161, D-1243): the font's kerning for each printable ASCII pair"
    )
    lines.append(
        "// that has one, in font units, as the bake's basic layout reads it (FT_Get_Kerning)."
    )
    lines.append("export const SEGOE_UI_KERN_UNITS: Record<string, number> = {")
    pairs = [f"{json.dumps(pair)}: {value}," for pair, value in kern.items()]
    for start in range(0, len(pairs), 8):
        lines.append("  " + " ".join(pairs[start : start + 8]))
    lines.append("}")
    return ("\r\n".join(lines) + "\r\n").encode("utf-8")


def build() -> bytes:
    if not FONT.is_file():
        raise ValueError(f"the font is missing: {FONT.name}")
    font_sha = hashlib.sha256(FONT.read_bytes()).hexdigest()
    return render(font_units(FONT), font_kerning(FONT), font_sha)


FAULT_ENV = "EHP_WRITE_FAULT"


def write_new(target: Path, data: bytes, *, replace: bool) -> str | None:
    """Write `data` with no partial file left (Session 95 RULE-1); return an error or None.

    With `replace` the bytes go to `<target>.ehp-tmp` (created exclusively) and then replace
    `target` in one `os.replace`; without it `target` itself is created exclusively. A write,
    flush or close error removes the file this call created, so `target` keeps its old bytes
    (or stays absent). `EHP_WRITE_FAULT=1` raises that error after the create, for the test.
    """
    made = target.with_name(target.name + ".ehp-tmp") if replace else target
    try:
        fh = made.open("xb")
    except FileExistsError:
        return f"{made.name} exists"
    except OSError as exc:
        return f"create {made.name}: {type(exc).__name__}"
    try:
        with fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
            if os.environ.get(FAULT_ENV) == "1":
                raise OSError("injected write fault")
        if replace:
            os.replace(made, target)
    except OSError as exc:
        made.unlink(missing_ok=True)
        return f"write {made.name}: {exc}"
    return None


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--out", type=Path, help="write the module to this new file")
    mode.add_argument("--write", action="store_true", help="replace the tracked module")
    mode.add_argument("--check", action="store_true", help="compare the tracked module")
    args = parser.parse_args()
    try:
        data = build()
    except (OSError, ValueError) as exc:
        print(f"REFUSED: {exc}")
        return 1
    digest = hashlib.sha256(data).hexdigest()
    if args.check:
        now = MODULE.read_bytes() if MODULE.is_file() else b""
        same = now == data
        print(
            f"segoe-units check: module {len(now)} bytes, generated {len(data)} bytes,"
            f" sha256 {digest[:16]}, {'match' if same else 'MISMATCH'}"
        )
        return 0 if same else 1
    if args.out is not None:
        problem = write_new(args.out, data, replace=False)
        if problem is not None:
            print(f"REFUSED: {problem}")
            return 1
        print(f"segoe-units: wrote {len(data)} bytes, sha256 {digest[:16]}, to --out")
        return 0
    problem = write_new(MODULE, data, replace=True)
    if problem is not None:
        print(f"REFUSED: {problem}; the tracked module keeps its bytes")
        return 1
    crlf = data.count(b"\r\n")
    print(f"segoe-units: wrote {MODULE.name}, {len(data)} bytes, {crlf} CRLF, sha256 {digest[:16]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
